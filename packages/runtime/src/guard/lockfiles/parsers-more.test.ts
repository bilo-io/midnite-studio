import { describe, expect, it } from 'vitest';

import { parseGemfileLock, parseLockfile, parsePackageResolved, parsePoetryLock, parseUvLock, parseYarnBerryLock, parseYarnLock } from './parsers';

const opts = { path: '/r/lock' };

describe('lockfile parsers: berry, poetry, uv, Gemfile, Package.resolved (Phase 122 Theme B)', () => {
  const berry = `# This file is generated by running "yarn install"

__metadata:
  version: 8
  cacheKey: 10c0

"@babel/core@npm:^7.0.0, @babel/core@npm:^7.1.0":
  version: 7.24.0
  resolution: "@babel/core@npm:7.24.0"
  dependencies:
    lodash: "npm:^4.17.0"
  checksum: abc

"lodash@npm:^4.17.0":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."

"fsevents@patch:fsevents@npm%3A2.3.3#~builtin<compat/fsevents>":
  version: 2.3.3
  resolution: "fsevents@patch:fsevents@npm%3A2.3.3#~builtin<compat/fsevents>::version=2.3.3"
`;
  it('reads berry registry packages and skips workspace/patch protocols', () => {
    const pkgs = parseYarnBerryLock(berry, { ...opts, directNames: new Set(['lodash']) });
    expect(pkgs.map((p) => `${p.name}@${p.version}:${p.direct}`)).toEqual(['@babel/core@7.24.0:false', 'lodash@4.17.21:true']);
  });
  it('parseYarnLock hands a berry file to the berry reader', () => {
    expect(parseYarnLock(berry, opts)).toHaveLength(2);
    expect(parseLockfile('yarn.lock', berry, opts)).toHaveLength(2);
  });

  it('reads poetry.lock and skips path/git packages', () => {
    const body = `[[package]]
name = "Requests_OAuthlib"
version = "1.3.1"

[[package]]
name = "local-thing"
version = "0.1.0"

[package.source]
type = "directory"
url = "../local"

[[package]]
name = "urllib3"
version = "2.2.1"

[package.source]
type = "legacy"
url = "https://example.test/simple"
`;
    expect(parsePoetryLock(body, opts).map((p) => `${p.name}@${p.version}`)).toEqual(['requests-oauthlib@1.3.1', 'urllib3@2.2.1']);
  });

  it('reads uv.lock registry packages only', () => {
    const body = `version = 1

[[package]]
name = "my-app"
version = "0.1.0"
source = { editable = "." }

[[package]]
name = "Certifi"
version = "2024.2.2"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "gitdep"
version = "1.0.0"
source = { git = "https://github.com/x/y" }
`;
    expect(parseUvLock(body, { ...opts, directNames: new Set(['certifi']) })).toEqual([
      { ecosystem: 'PyPI', name: 'certifi', version: '2024.2.2', direct: true, path: '/r/lock' },
    ]);
  });

  it('reads Gemfile.lock specs, marks DEPENDENCIES direct, strips platform suffixes', () => {
    const body = `GIT
  remote: https://github.com/x/y.git
  specs:
    gitgem (0.0.1)

GEM
  remote: https://rubygems.org/
  specs:
    nokogiri (1.16.2-arm64-darwin)
      racc (~> 1.4)
    racc (1.7.3)
    rails (7.1.3)

PLATFORMS
  arm64-darwin

DEPENDENCIES
  rails (~> 7.1)
  nokogiri!

BUNDLED WITH
   2.5.6
`;
    const pkgs = parseGemfileLock(body, opts);
    expect(pkgs.map((p) => `${p.name}@${p.version}:${p.direct}`)).toEqual(['nokogiri@1.16.2:true', 'racc@1.7.3:false', 'rails@7.1.3:true']);
    expect(pkgs.every((p) => p.ecosystem === 'RubyGems')).toBe(true);
  });

  it('reads Package.resolved v1 and v2 and skips unversioned pins', () => {
    const v2 = JSON.stringify({
      version: 2,
      pins: [
        { identity: 'swift-nio', location: 'https://github.com/apple/swift-nio.git', state: { revision: 'a', version: '2.65.0' } },
        { identity: 'branchy', location: 'https://github.com/x/branchy', state: { branch: 'main', revision: 'b' } },
      ],
    });
    const v1 = JSON.stringify({
      version: 1,
      object: { pins: [{ package: 'Alamofire', repositoryURL: 'https://github.com/Alamofire/Alamofire.git', state: { version: '5.8.1' } }] },
    });
    expect(parsePackageResolved(v2, opts)).toEqual([{ ecosystem: 'SwiftURL', name: 'github.com/apple/swift-nio', version: '2.65.0', direct: false, path: '/r/lock' }]);
    expect(parsePackageResolved(v1, opts)[0]?.name).toBe('github.com/Alamofire/Alamofire');
  });

  it('parseLockfile never throws on a malformed Package.resolved', () => {
    expect(parseLockfile('Package.resolved', '{not json', opts)).toEqual([]);
  });

  it('reads a berry alias as the real package, ignoring __metadata', () => {
    const body = '__metadata:\n  version: 8\n"string-width-cjs@npm:string-width@^4.2.0":\n  version: 4.2.3\n  resolution: "string-width-cjs@npm:string-width@npm:4.2.3"\n';
    expect(parseYarnBerryLock(body, opts).map((p) => `${p.name}@${p.version}`)).toEqual(['string-width@4.2.3']);
  });
  it('reads a CRLF Gemfile.lock', () => {
    const body = 'GEM\r\n  remote: https://rubygems.org/\r\n  specs:\r\n    rack (3.0.0)\r\n\r\nDEPENDENCIES\r\n  rack\r\n';
    expect(parseGemfileLock(body, opts).map((p) => `${p.name}@${p.version}:${p.direct}`)).toEqual(['rack@3.0.0:true']);
  });
  it('normalises scp-style SwiftPM locations', () => {
    const body = JSON.stringify({ pins: [{ location: 'git@github.com:apple/swift-nio.git', state: { version: '1.0.0' } }] });
    expect(parsePackageResolved(body, opts)[0]?.name).toBe('github.com/apple/swift-nio');
  });
  it('skips a poetry git package even with brackets in its source', () => {
    const body = '[[package]]\nname = "g"\nversion = "1"\n\n[package.source]\nurl = "https://x/[y]"\ntype = "git"\n';
    expect(parsePoetryLock(body, opts)).toEqual([]);
  });
});
