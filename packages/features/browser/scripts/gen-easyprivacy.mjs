#!/usr/bin/env node
/**
 * Regenerate `main/data/easyprivacy.generated.ts` from EasyPrivacy (Phase 117 Theme E).
 *
 *   node packages/features/browser/scripts/gen-easyprivacy.mjs [path-or-url]
 *
 * Keeps only the host-anchored network rules (`||host…` and `@@||host…`) — the only form
 * `main/filter-list.ts` models; everything else it would count and drop anyway. The output is a
 * TS module (not a `.txt` import) so it bundles identically under esbuild (both app bundlers) and
 * vitest. The licence ships beside it in `main/data/EASYPRIVACY-LICENCE.md`; refreshing the
 * bundled copy is a deliberate commit, never a runtime fetch (Phase 115: no feed without a switch).
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = process.argv[2] ?? 'https://easylist.to/easylist/easyprivacy.txt';
const text = src.startsWith('http') ? await (await fetch(src)).text() : readFileSync(src, 'utf8');
const header = (k) => new RegExp(`^! ${k}: (.*)$`, 'm').exec(text)?.[1]?.trim() ?? '';
const kept = text.split('\n').filter((l) => (l.startsWith('||') || l.startsWith('@@||')) && !l.includes('##'));
const meta = {
  source: 'https://easylist.to/easylist/easyprivacy.txt',
  version: header('Version'),
  lastModified: header('Last modified'),
  sourceSha256: createHash('sha256').update(text).digest('hex'),
  licence: 'GPL-3.0-or-later OR CC-BY-SA-3.0 (dual) — see EASYPRIVACY-LICENCE.md',
  keptRules: kept.length,
};
const out = `// GENERATED by scripts/gen-easyprivacy.mjs — do not edit. EasyPrivacy, © The EasyList authors
// (https://easylist.to/), dual-licensed GPL-3.0-or-later / CC BY-SA 3.0; see EASYPRIVACY-LICENCE.md.
export const EASYPRIVACY_META = ${JSON.stringify(meta, null, 2)} as const;

export const EASYPRIVACY_RULES: string = ${JSON.stringify(kept.join('\n'))};
`;
writeFileSync(fileURLToPath(new URL('../main/data/easyprivacy.generated.ts', import.meta.url)), out);
console.log(meta);
