import { createHash, randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import {
  CLIPBOARD_HISTORY_MAX_BYTES,
  CLIPBOARD_HISTORY_MAX_ENTRIES,
  CLIPBOARD_IMAGE_MAX_BYTES,
  CLIPBOARD_POLL_MS,
  CLIPBOARD_SKIP_MARKERS,
  CLIPBOARD_TEXT_MAX_BYTES,
  ClipboardEntryIdSchema,
  failure,
  ok,
  type ClipboardEntry,
  type GitOpResult,
} from '@midnite/studio-shared';
import { z } from 'zod';

import type { CaptureClipboard, CaptureImage } from './port';

/**
 * Clipboard history (Phase 113 Theme K) — **off by default, and blind while off**.
 *
 * The clipboard has no change event, so while the user has history on, main looks every
 * {@link CLIPBOARD_POLL_MS}; while it is off there is no timer and nothing reads the clipboard at all.
 * What it keeps:
 *
 * - **text and images only** — files, rich text and app-private types are not history;
 * - **never a marked entry**: anything carrying `org.nspasteboard.ConcealedType`, `TransientType` or
 *   `AutoGeneratedType` is skipped, which is how 1Password, Bitwarden, KeePassXC and the macOS password
 *   AutoFill say "do not keep this";
 * - **capped**: at most {@link CLIPBOARD_HISTORY_MAX_ENTRIES} entries and
 *   {@link CLIPBOARD_HISTORY_MAX_BYTES} in all (the oldest go first); a single text over
 *   {@link CLIPBOARD_TEXT_MAX_BYTES} or image over {@link CLIPBOARD_IMAGE_MAX_BYTES} is not kept.
 *
 * It lives under the app's own data directory (`<dataDir>/clipboard/`: `history.json` and one PNG per
 * image), and Clear removes all of it. Copying the same thing twice moves it to the top, not a duplicate.
 */
export const CLIPBOARD_DIR = 'clipboard';
const HISTORY_FILE = 'history.json';
/** The wire carries a text entry's first few thousand characters; copy-back uses the whole text. */
export const CLIPBOARD_PREVIEW_CHARS = 2_000;

const StoredSchema = z.discriminatedUnion('kind', [
  z.object({
    id: ClipboardEntryIdSchema,
    kind: z.literal('text'),
    createdAt: z.number(),
    bytes: z.number(),
    hash: z.string(),
    text: z.string(),
  }),
  z.object({
    id: ClipboardEntryIdSchema,
    kind: z.literal('image'),
    createdAt: z.number(),
    bytes: z.number(),
    hash: z.string(),
    width: z.number().int().positive(),
    height: z.number().int().positive(),
  }),
]);
type Stored = z.infer<typeof StoredSchema>;
const HistorySchema = z.object({ version: z.literal(1), entries: z.array(StoredSchema) });

export type Timers = {
  setInterval: (fn: () => void, ms: number) => unknown;
  clearInterval: (handle: unknown) => void;
};

export type ClipboardHistory = {
  /** Starts polling (idempotent). */
  start: () => void;
  /** Stops polling (idempotent). Kept entries stay until cleared. */
  stop: () => void;
  running: () => boolean;
  /** One look at the clipboard — the poll's body, exported for tests. Resolves true when it kept something. */
  tick: () => Promise<boolean>;
  list: () => Promise<ClipboardEntry[]>;
  copy: (id: string) => Promise<GitOpResult>;
  remove: (id: string) => Promise<GitOpResult>;
  clear: () => Promise<GitOpResult>;
  /** The absolute path of an image entry's PNG, for the file resolver. */
  imagePath: (fileName: string) => string;
};

const sha = (data: Uint8Array | string) => createHash('sha256').update(data).digest('hex');

/** Whether the clipboard carries a "do not keep" marker. */
export function isMarked(
  clipboard: Pick<CaptureClipboard, 'availableFormats' | 'has'>,
  formats: string[],
): boolean {
  const markers: readonly string[] = CLIPBOARD_SKIP_MARKERS;
  if (formats.some((f) => markers.includes(f))) return true;
  return CLIPBOARD_SKIP_MARKERS.some((marker) => {
    try {
      return clipboard.has(marker);
    } catch {
      return false;
    }
  });
}

export function createClipboardHistory(deps: {
  dataDir: string;
  clipboard: CaptureClipboard;
  imageFromPng: (bytes: Uint8Array) => CaptureImage;
  onChanged: () => void;
  now?: () => number;
  timers?: Timers;
  pollMs?: number;
}): ClipboardHistory {
  const dir = join(deps.dataDir, CLIPBOARD_DIR);
  const file = join(dir, HISTORY_FILE);
  const now = deps.now ?? Date.now;
  const timers: Timers = deps.timers ?? {
    setInterval: (fn, ms) => setInterval(fn, ms),
    clearInterval: (h) => clearInterval(h as ReturnType<typeof setInterval>),
  };
  let handle: unknown = null;
  let busy = false;
  /** What the last look saw, so an unchanged clipboard costs no hashing of images. */
  let lastSignature: string | null = null;
  let entries: Stored[] | null = null;
  let chain: Promise<unknown> = Promise.resolve();

  const load = async (): Promise<Stored[]> => {
    if (entries) return entries;
    try {
      const parsed = HistorySchema.safeParse(JSON.parse(await readFile(file, 'utf8')));
      entries = parsed.success ? parsed.data.entries : [];
    } catch {
      entries = [];
    }
    return entries;
  };

  const save = async (next: Stored[]) => {
    await mkdir(dir, { recursive: true });
    const tmp = `${file}.tmp`;
    await writeFile(tmp, JSON.stringify({ version: 1, entries: next }));
    await rename(tmp, file);
    entries = next;
  };

  const serial = <T>(run: () => Promise<T>): Promise<T> => {
    const next = chain.then(run);
    chain = next.catch(() => undefined);
    return next;
  };

  const pngPath = (id: string) => join(dir, `${id}.png`);

  /** Applies the caps: count first, then bytes, oldest out. Returns what to keep and what to delete. */
  const capped = (list: Stored[]): { keep: Stored[]; gone: Stored[] } => {
    const keep: Stored[] = [];
    const gone: Stored[] = [];
    let total = 0;
    for (const entry of list) {
      if (
        keep.length < CLIPBOARD_HISTORY_MAX_ENTRIES &&
        total + entry.bytes <= CLIPBOARD_HISTORY_MAX_BYTES
      ) {
        keep.push(entry);
        total += entry.bytes;
      } else {
        gone.push(entry);
      }
    }
    return { keep, gone };
  };

  const keepEntry = (entry: Stored, png?: Uint8Array) =>
    serial(async () => {
      const current = await load();
      const existing = current.find((e) => e.hash === entry.hash);
      const rest = current.filter((e) => e.hash !== entry.hash);
      // The same content again moves to the top under its old id (its PNG is already on disk).
      const top = existing ? { ...existing, createdAt: entry.createdAt } : entry;
      if (!existing && png) {
        await mkdir(dir, { recursive: true });
        await writeFile(pngPath(entry.id), png);
      }
      const { keep, gone } = capped([top, ...rest]);
      await save(keep);
      for (const old of gone) if (old.kind === 'image') await rm(pngPath(old.id), { force: true });
    });

  const tick = async (): Promise<boolean> => {
    if (busy) return false;
    busy = true;
    try {
      const { clipboard } = deps;
      let formats: string[];
      try {
        formats = clipboard.availableFormats();
      } catch {
        return false;
      }
      if (formats.length === 0) return false;
      // A marked entry (a password manager's copy) is never read, not even into the comparison below:
      // the markers are checked on the formats alone, before any text leaves the pasteboard.
      if (isMarked(clipboard, formats)) {
        lastSignature = `marked:${formats.join('|')}`;
        return false;
      }
      const text = formats.some((f) => f.startsWith('text/plain')) ? clipboard.readText() : '';
      const hasImage = formats.some((f) => f.startsWith('image/'));
      const signature = `${formats.join('|')}\n${text}`;
      // Unchanged since the last look (an image is re-checked only when the formats or text move).
      if (signature === lastSignature) return false;
      lastSignature = signature;
      const id = `clip-${randomBytes(6).toString('hex')}`;
      if (hasImage) {
        const image = clipboard.readImage();
        if (!image.isEmpty()) {
          const png = image.toPNG();
          if (png.byteLength > CLIPBOARD_IMAGE_MAX_BYTES) return false;
          const { width, height } = image.getSize();
          await keepEntry(
            {
              id,
              kind: 'image',
              createdAt: now(),
              bytes: png.byteLength,
              hash: sha(png),
              width,
              height,
            },
            png,
          );
          deps.onChanged();
          return true;
        }
      }
      if (text.trim().length === 0) return false;
      const bytes = Buffer.byteLength(text, 'utf8');
      if (bytes > CLIPBOARD_TEXT_MAX_BYTES) return false;
      await keepEntry({ id, kind: 'text', createdAt: now(), bytes, hash: sha(text), text });
      deps.onChanged();
      return true;
    } finally {
      busy = false;
    }
  };

  const toWire = (entry: Stored): ClipboardEntry =>
    entry.kind === 'text'
      ? {
          id: entry.id,
          kind: 'text',
          createdAt: entry.createdAt,
          bytes: entry.bytes,
          text: entry.text.slice(0, CLIPBOARD_PREVIEW_CHARS),
        }
      : {
          id: entry.id,
          kind: 'image',
          createdAt: entry.createdAt,
          bytes: entry.bytes,
          width: entry.width,
          height: entry.height,
        };

  return {
    start: () => {
      if (handle !== null) return;
      // The clipboard as it is now is not history: only what the user copies from here on.
      lastSignature = null;
      handle = timers.setInterval(
        () => void tick().catch(() => undefined),
        deps.pollMs ?? CLIPBOARD_POLL_MS,
      );
      void (async () => {
        try {
          const formats = deps.clipboard.availableFormats();
          const text = formats.some((f) => f.startsWith('text/plain'))
            ? deps.clipboard.readText()
            : '';
          lastSignature = `${formats.join('|')}\n${text}`;
        } catch {
          lastSignature = null;
        }
      })();
    },
    stop: () => {
      if (handle === null) return;
      timers.clearInterval(handle);
      handle = null;
    },
    running: () => handle !== null,
    tick,
    list: async () => (await load()).map(toWire),
    copy: async (id) => {
      const entry = (await load()).find((e) => e.id === id);
      if (!entry) return failure('That clipboard entry is gone.');
      try {
        if (entry.kind === 'text') deps.clipboard.writeText(entry.text);
        else deps.clipboard.writeImage(deps.imageFromPng(await readFile(pngPath(entry.id))));
        return ok();
      } catch (error) {
        return failure(error instanceof Error ? error.message : String(error));
      }
    },
    remove: (id) =>
      serial(async () => {
        const current = await load();
        const entry = current.find((e) => e.id === id);
        if (!entry) return ok();
        await save(current.filter((e) => e.id !== id));
        if (entry.kind === 'image') await rm(pngPath(entry.id), { force: true });
        deps.onChanged();
        return ok();
      }),
    clear: () =>
      serial(async () => {
        const current = await load();
        await save([]);
        for (const entry of current)
          if (entry.kind === 'image') await rm(pngPath(entry.id), { force: true });
        deps.onChanged();
        return ok();
      }),
    imagePath: (fileName) => join(dir, fileName),
  };
}
