import { EGRESS_ENTRIES, PRIVACY_SWITCHES, PRIVACY_SWITCH_DEFAULTS, type EgressHost } from './egress';

/**
 * Phase 115 Theme G — the privacy statement, rendered from the egress registry.
 *
 * `docs/PRIVACY.md` is this function's output. The outbound tables come from `EGRESS_ENTRIES`, so a new host
 * changes the document; the storage and inbound sections are hand-written below and describe what Themes B to F
 * of Phase 115 built. `privacy-doc.test.ts` fails when the committed file is stale; run `moon run root:privacy-doc`
 * to regenerate it. Pure and zod-free, per `shared`'s boundary.
 */

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const hostCell = (host: string): string => (host === '*' ? 'any address you type' : `\`${host}\``);

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cols: readonly string[]) => `| ${cols.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n');
}

function switchCell(e: EgressHost): string {
  if (!e.switch) return '—';
  return `${PRIVACY_SWITCHES[e.switch]} (${PRIVACY_SWITCH_DEFAULTS[e.switch] ? 'on' : 'off'} by default)`;
}

function rows(entries: readonly EgressHost[], withSwitch: boolean): string[][] {
  return entries.map((e) => [hostCell(e.host), cell(e.owner), cell(e.sends), ...(withSwitch ? [cell(switchCell(e))] : [])]);
}

export function renderPrivacyDoc(entries: readonly EgressHost[] = EGRESS_ENTRIES): string {
  const automatic = entries.filter((e) => e.trigger === 'automatic');
  const feeds = entries.filter((e) => e.trigger === 'feed');
  const user = entries.filter((e) => e.trigger === 'user');
  const head = ['Host', 'Feature', 'What is sent'];
  const headSwitch = [...head, 'Switch'];
  return `<!-- Generated by \`moon run root:privacy-doc\` from packages/shared/src/egress.ts. Do not edit by hand. -->

# Privacy

Midnite Studio is a desktop app. It has no account, no analytics and no telemetry, and it runs no server of
ours. This page answers three questions: what leaves your Mac, what stays on it and how it is kept, and who can
reach in.

## 1. What leaves this Mac

Every outbound host is listed in one registry in the source, and the app refuses to contact a host that is not
on it. The tables below are generated from that registry, so they cannot drift from what the app does.

**Settings ▸ Privacy ▸ Automatic network calls** has one switch per automatic call and a master switch,
"Turn off all automatic network", which overrides the rest without changing their saved positions.

### Automatic calls

The app makes these on its own, without you asking, while the feature is in use. Each can be turned off.

${table(headSwitch, rows(automatic, true))}

### Scheduled feeds

Pulled whole and matched on this Mac; nothing about you is sent. Off by default.

${table(headSwitch, rows(feeds, true))}

### Only when you ask

These happen because you started something: a search, a download, a request you composed.

${table(head, rows(user, false))}

The Launcher is a separate app. Its update and catalog checks are listed above under their switches; the Launcher
does not read those switches yet, so today they run at start regardless.

## 2. What stays on this Mac, and how it is kept

- **Credentials** (API keys, forge tokens) are held in the macOS Keychain through Electron's \`safeStorage\`.
  The window never receives them back, only whether one exists. When the Keychain is unavailable, a key is kept
  in memory for the session instead of on disk, and the app says so.
- **History** (terminal scrollback, archived session transcripts, chats, logs) is written to your user data
  folder with owner-only permissions: folders \`0700\`, files \`0600\`. It is not encrypted by the app; macOS file
  permissions and FileVault protect it at rest. **Settings ▸ Privacy ▸ Local history** keeps it forever by
  default, or for 90, 30 or 7 days, and "Clear all local history" removes scrollback, archived transcripts and
  logs after showing what will go. Chats are yours and are never cleared by it.
- **Secrets are scrubbed before they reach disk.** Log records, chats and archived transcripts pass through a
  redactor that removes the values held in your vault and common key shapes. Live scrollback stays exact.
- **Claude and Codex.** The app reads the local history those tools keep, for usage totals and conversation
  lookup, and says so in Settings ▸ Privacy. You can switch that off. It never writes to their settings, your
  \`.mcp.json\` or \`~/.codex/config.toml\`, and a test fails on any code that tries.

## 3. Who can reach in

- **Sharing your media library on the local network** is off until you start it. It binds one private address
  you pick, never a public one. Browse pages need an access token; streams, posters and transcodes need a signed
  link that expires after six hours and stops working when you regenerate the token.
- **The terminal broker and the MCP server** are Unix sockets guarded by file permissions, so only your macOS
  user can reach them. A process already running as you can connect; see \`SECURITY.md\`.
- **The app window** runs under a content-security policy that allows scripts only from the app itself and its
  one startup theme script, and allows network connections only to the hosts above.
`;
}
