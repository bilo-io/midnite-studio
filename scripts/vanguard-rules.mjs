#!/usr/bin/env node
// Regenerates packages/features/vanguard/main/malware/bundled-rules.ts from rules/*.yar (Phase 120 Theme F).
// The .yar files are the source of truth (a real `yara` reads them); the feature's main half is bundled, so
// it cannot read them off disk at runtime and embeds this string instead. A vitest fails when it is stale.
// Usage: node scripts/vanguard-rules.mjs [--check]
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'features', 'vanguard');
const out = join(root, 'main', 'malware', 'bundled-rules.ts');

/** Every file under rules/ (the .yar files and all fixtures), as sorted relative paths. */
function ownFiles(dir = join(root, 'rules'), rel = '') {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    if (e.isDirectory()) out.push(...ownFiles(join(dir, e.name), `${rel}${e.name}/`));
    else if (e.isFile()) out.push(`${rel}${e.name}`);
  }
  return out;
}

export function render() {
  const digests = ownFiles().map((f) => createHash('sha256').update(readFileSync(join(root, 'rules', f))).digest('hex'));
  const files = readdirSync(join(root, 'rules')).filter((f) => f.endsWith('.yar')).sort();
  const sources = files.map((f) => readFileSync(join(root, 'rules', f), 'utf8'));
  return `// GENERATED by scripts/vanguard-rules.mjs from rules/*.yar. Do not edit; run the script.
/** Every bundled rule file, concatenated in filename order. */
export const BUNDLED_RULES_SOURCE: string = ${JSON.stringify(sources.join('\n'))};
/**
 * SHA-256 of exactly Vanguard's own rule files and fixtures. They contain every pattern they detect, so a
 * scan skips a file only when its bytes hash to one of these; a path is never enough (an attacker can drop
 * a file under any directory name).
 */
export const OWN_FILE_DIGESTS: readonly string[] = ${JSON.stringify([...new Set(digests)].sort(), null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (current !== next) { console.error('bundled-rules.ts is stale: run node scripts/vanguard-rules.mjs'); process.exit(1); }
  } else writeFileSync(out, next);
}
