function patchOllama(cfg: { installed: typeof INSTALLED; library: typeof LIBRARY; now: number }): void {
  const w = window as unknown as { midniteStudio?: { ollama: Record<string, unknown> } };
  const go = (): void => {
    const o = w.midniteStudio?.ollama;
    if (!o) return void setTimeout(go, 0);
    o['list'] = async () => ({
      ok: true,
      value: {
        models: cfg.installed.map((m) => ({
          name: m.name,
          model: m.name,
          modifiedAt: new Date(cfg.now - m.ago * 86_400_000).toISOString(),
          size: Math.round(m.size),
          digest: 'sha256:' + m.name.replace(/[^a-z0-9]/g, '').padEnd(12, '0').slice(0, 12),
          details: { format: 'gguf', family: m.family, families: [m.family], parameterSize: m.parameterSize, quantizationLevel: m.quantizationLevel },
        })),
      },
    });
    o['show'] = async (req: { model: string }) => {
      const m = cfg.installed.find((x) => x.name === req.model);
      const base = req.model.split(':')[0];
      const caps = base === 'qwen3.5' ? ['completion', 'vision', 'tools', 'thinking'] : base.startsWith('nomic') ? ['embedding'] : ['completion', 'tools'];
      return {
        ok: true,
        value: {
          capabilities: caps,
          contextLength: base === 'qwen3.5' ? 262144 : 131072,
          parameters: 'num_ctx 65536\ntemperature 0.6\ntop_p 0.95\ntop_k 20',
          details: m ? { format: 'gguf', family: m.family, parameterSize: m.parameterSize, quantizationLevel: m.quantizationLevel } : undefined,
          modelfile:
            `# Modelfile generated by "ollama show"\nFROM /Users/bilo/.ollama/models/blobs/sha256-a3de86cd1c13\nTEMPLATE {{ .Prompt }}\nRENDERER ${base}\nPARSER ${base}\nPARAMETER num_ctx 65536\nPARAMETER temperature 0.6\nPARAMETER top_k 20\nPARAMETER top_p 0.95\nLICENSE """Apache License 2.0"""`,
          template: '{{ .Prompt }}',
          license: 'Apache License 2.0',
        },
      };
    };
    o['search'] = async (req?: { query?: string }) => {
      const q = (req?.query ?? '').toLowerCase();
      return { ok: true, value: { items: cfg.library.filter((i) => !q || i.name.includes(q)), stale: false, updatedAt: new Date(cfg.now).toISOString() } };
    };
  };
  go();
}

async function openModels(page: Page): Promise<void> {
  await installMockBridge(page, roadmapFixtures({ ollamaModels: INSTALLED.map((m) => ({ name: m.name, size: m.size })) } as never), { cspGuard: false });
  await page.addInitScript(patchOllama, { installed: INSTALLED, library: LIBRARY, now: Date.now() });
  await preparePage(page, { theme: 'light' });
  await page.goto('/');
  await expect(page.getByRole('navigation', { name: 'Views' })).toBeVisible({ timeout: 30_000 });
  await expect(async () => {
    await gotoView(page, 'Models');
    await expect(page.getByText('qwen3.5:9b').first()).toBeVisible({ timeout: 800 });
  }).toPass({ timeout: 8000 });
  await placeCursor(page, 900, 600);
  await settlePage(page, 1200);
}

test('models-light', async ({ page }) => {
  await openModels(page);
  const name = (n: string) => page.getByText(n, { exact: true }).first();
  const rec = new Recorder(page, 'models-light');
  await rec.start();
  await page.waitForTimeout(600);
  await glideTo(page, name('gemma3:12b'), 900, { x: 0.5, y: 0.5 });
  await page.waitForTimeout(200);
  await glideTo(page, name('llama3.2:3b'), 600, { x: 0.5, y: 0.5 });
  await page.waitForTimeout(200);
  await glideTo(page, name('qwen3.5:9b'), 600, { x: 0.5, y: 0.5 });
  await click(page);
  await expect(page.getByText('Fit for agents')).toBeVisible();
  await page.waitForTimeout(500);
  await glide(page, 900, 620, 900);
  await page.waitForTimeout(1200);
  await page.keyboard.press('Escape');
  await page.waitForTimeout(350);
  await glideTo(page, page.getByRole('tab', { name: 'Discover' }), 900);
  await click(page);
  const search = page.getByPlaceholder(/Search ollama\.com/);
  await glideTo(page, search, 700, { x: 0.25, y: 0.5 });
  await click(page);
  await typeSlow(page, 'qwen', 90);
  await page.waitForTimeout(1200);
  await glide(page, 700, 330, 900);
  await page.waitForTimeout(1300);
  await rec.stop();
});
